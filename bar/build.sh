#!/usr/bin/env bash
# builds build/bar (or build/debug/bar with --debug).
#
# usage: bar/build.sh [--debug] [--left "modules"] [--center "modules"] [--right "modules"]
#                     [--no-wallpaper]
#   --left, --center, --right  the modules of each section, left to right, replacing the
#                              defaults below. "" leaves a section empty.
#   --no-wallpaper             leaves the wallpaper out.
#
# a module is bar/modules/<name>.c, defining <name>Module. only the modules listed are
# compiled and linked (with the libraries they need), and build/bar-modules.c is generated
# to list them in order.
source "$(dirname "$0")/../common/build.sh"

left=(workspaces mpris window)
center=(clock)
right=(tray dnd battery temp cpu memory disk connectivity volume)
wallpaper=true

arguments=()
while (($#)); do
  case $1 in
    --left) read -ra left <<< "${2-}"; shift ;;
    --center) read -ra center <<< "${2-}"; shift ;;
    --right) read -ra right <<< "${2-}"; shift ;;
    --no-wallpaper) wallpaper=false ;;
    *) arguments+=("$1") ;;
  esac
  shift
done
BuildArguments "${arguments[@]+"${arguments[@]}"}"

modules=("${left[@]+"${left[@]}"}" "${center[@]+"${center[@]}"}" "${right[@]+"${right[@]}"}")
for module in "${modules[@]+"${modules[@]}"}"; do
  if [[ ! -f bar/modules/$module.c ]]; then
    echo "build: there is no module $module (bar/modules/$module.c)" >&2
    exit 1
  fi
done

# connectivity is the bluetooth and network modules in one pill, so it needs their files, and
# can't be listed alongside them (they would each start twice).
compiled=("${modules[@]+"${modules[@]}"}")
if printf '%s\n' "${modules[@]+"${modules[@]}"}" | grep -qx connectivity; then
  if printf '%s\n' "${modules[@]}" | grep -qxE 'bluetooth|network'; then
    echo "build: connectivity already includes bluetooth and network" >&2
    exit 1
  fi
  compiled+=(bluetooth network)
fi

# the generated table of modules.
table() {
  local name=$1
  shift
  printf 'const BarModule *const %s[] = {' "$name"
  local module
  for module in "$@"; do printf '&%sModule, ' "$module"; done
  printf 'nullptr};\n'
}
mkdir -p build
{
  echo "// generated by bar/build.sh: the modules built in, in order."
  echo
  echo '#include "module.h"'
  echo
  for module in $(printf '%s\n' "${modules[@]+"${modules[@]}"}" | sort -u); do
    echo "extern const BarModule ${module}Module;"
  done
  echo
  table barLeft "${left[@]+"${left[@]}"}"
  table barCenter "${center[@]+"${center[@]}"}"
  table barRight "${right[@]+"${right[@]}"}"
  echo "const bool barWallpaper = $wallpaper;"
} > build/bar-modules.c.new
# only replaced when it changes, so it does not look newer than it is.
if cmp -s build/bar-modules.c.new build/bar-modules.c; then
  rm build/bar-modules.c.new
else
  mv build/bar-modules.c.new build/bar-modules.c
fi

packages=(wayland-client xkbcommon cairo pangocairo libsystemd libpulse)
sources=(
  bar/main.c
  bar/calendar.c
  bar/dbus.c
  bar/hyprland.c
  bar/json.c
  bar/pulse.c
  bar/wallpaper.c
  build/bar-modules.c
  common/draw.c
  common/input.c
  common/instance.c
  common/memory.c
  common/process.c
  common/strbuf.c
  common/wayland.c
)
for module in $(printf '%s\n' "${compiled[@]+"${compiled[@]}"}" | sort -u); do
  sources+=("bar/modules/$module.c")
done
# the tray has helpers of its own, and draws svg icons with librsvg.
if printf '%s\n' "${modules[@]+"${modules[@]}"}" | grep -qx tray; then
  sources+=(bar/tray/icon.c bar/tray/menu.c)
  packages+=(librsvg-2.0)
fi
common+=(-Ibar)
BuildApp bar
